# ============================================================================
# CTParser Reexports Tests
# ============================================================================
# This file tests the reexport of symbols from `CTParser`. It verifies that
# the `@def` macro and related parsing utilities are properly exported by
# `OptimalControl` for user-friendly problem definition, and that they work
# from a module that has none of the implementation packages in scope (#967).

module TestCtparser

using Test: Test
using OptimalControl # using is mandatory since we test exported symbols
using NLPModelsIpopt: NLPModelsIpopt # arms the Ipopt solver for the solves below

const VERBOSE = isdefined(Main, :TestOptions) ? Main.TestOptions.VERBOSE : true
const SHOWTIMING = isdefined(Main, :TestOptions) ? Main.TestOptions.SHOWTIMING : true

const CurrentModule = TestCtparser

# `@def` and `@init` called from modules that have neither `CTModels`, `ExaModels` nor
# `CTBase` in scope. Since CTParser 0.9.6 the generated code holds the modules themselves,
# so it needs no name at the call site (#967).
module DefImportOnly
using OptimalControl: OptimalControl # the module name only, as `import OptimalControl`
const OCP = OptimalControl.@def begin
    t ∈ [0, 1], time
    x ∈ R², state
    u ∈ R, control
    x(0) == [-1, 0]
    x(1) == [0, 0]
    ẋ(t) == [x₂(t), u(t)]
    ∫(0.5u(t)^2) → min
end
guess() = OptimalControl.@init OCP begin
    u(t) := 0.1
end
end

module DefMacroOnly
using OptimalControl: @def, @init
const OCP = @def begin
    t ∈ [0, 1], time
    x ∈ R, state
    u ∈ R, control
    x(0) == 1
    ẋ(t) == u(t)
    ∫(x(t)^2 + u(t)^2) → min
end
guess() = @init OCP begin
    x(t) := 1 - t
end
end

function test_ctparser()
    Test.@testset "CTParser reexports" verbose = VERBOSE showtiming = SHOWTIMING begin
        Test.@testset "Macros" begin
            Test.@test isdefined(OptimalControl, Symbol("@def"))
            Test.@test isdefined(CurrentModule, Symbol("@def"))
            Test.@test isdefined(OptimalControl, Symbol("@init"))
            Test.@test isdefined(CurrentModule, Symbol("@init"))
        end

        Test.@testset "@def and @init are hygienic" begin
            for M in (DefImportOnly, DefMacroOnly)
                Test.@testset "$(nameof(M))" begin
                    for name in (:CTModels, :ExaModels, :CTBase)
                        Test.@test !isdefined(M, name)
                    end
                    Test.@test M.OCP isa OptimalControl.Model
                    Test.@test M.guess() isa OptimalControl.AbstractInitialGuess
                end
            end

            # The `:exa` backend builds its model from the code generated by `@def`.
            Test.@testset "solve, :adnlp and :exa" begin
                sol_adnlp = solve(DefImportOnly.OCP, :adnlp; display=false)
                sol_exa = solve(DefImportOnly.OCP, :exa; display=false)
                Test.@test successful(sol_adnlp)
                Test.@test successful(sol_exa)
                Test.@test objective(sol_adnlp) ≈ 6 rtol = 1e-3
                Test.@test objective(sol_exa) ≈ objective(sol_adnlp) rtol = 1e-6
                sol_init = solve(
                    DefImportOnly.OCP; init=DefImportOnly.guess(), display=false
                )
                Test.@test successful(sol_init)
            end
        end
    end
end

end # module

# Redefine in outer scope for TestRunner
test_ctparser() = TestCtparser.test_ctparser()
